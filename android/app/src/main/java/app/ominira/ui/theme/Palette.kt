    val onAction: Color,
    val actionSoft: Color,
    val sun: Color,
    val onSun: Color,
    val mint: Color,
    val forest: Color,
    val forestEdge: Color,
    val bandText: Color,
    val bandMuted: Color,
    val focus: Color,
    val ok: Color,
    val okSoft: Color,
    val caution: Color,
    val cautionSoft: Color,
    val danger: Color,
    val dangerSoft: Color,
    val info: Color,
    val infoSoft: Color,
    val modeVoice: Color,
    val modeSign: Color,
    val modeSwitch: Color,
    val modePlain: Color,
    val modeInk: Color,
    val scrim: Color,
    val dark: Boolean,
)

